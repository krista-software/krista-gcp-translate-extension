package com.kristasoft.extensions.ai.nlp.gcp.util.media;

import org.jvnet.hk2.annotations.Service;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import javax.inject.Inject;
import java.io.File;
import java.io.IOException;

@Service
public class JavaFileHandleHelper {

    private static final Logger logger = LoggerFactory.getLogger(JavaFileHandleHelper.class);

    @Inject
    private FileHandlerFactory fileHandlerFactory;

    public File convertFile(app.krista.model.base.File file) throws IOException {
        FileHandler fileHandler = fileHandlerFactory.getFileHandler();
        return fileHandler.convertFile(file);
    }

}

